export function getItemBasePrice(id: ItemId): number {
  const def = ITEMS[id];
  if (typeof def?.basePrice === 'number' && def.basePrice > 0) {
    return def.basePrice;
  }
  return FALLBACK_PRICES[id] ?? 12;
}

export function getItemInventoryGroup(id: ItemId): Exclude<InventoryFilterCategory, 'ALL'> {
  const def = ITEMS[id];
  if (def.inventoryGroup && def.inventoryGroup !== 'ALL') {
    return def.inventoryGroup;
  }
  if (def.category === 'EQUIPMENT') {
    return def.equipSlot === 'WEAPON' ? 'WEAPONS' : 'ARMOR';
  }
  if (def.category === 'TOOL') return 'TOOLS';
  if (POTION_ITEM_IDS.has(id)) return 'POTIONS';
  if (FOOD_ITEM_IDS.has(id)) return 'FOOD';
  if (MISC_ITEM_IDS.has(id) || def.category === 'COMBAT') return 'MISCELLANEOUS';
  return 'MATERIALS';
}
